  /* -------------------------------------------------------- POSE OBJECT */
  // js/kuro-state.js fills one of these every frame and hands it to
  // drawBody/drawEyes.
  function defaultPose() {
    return {
      frame: "sit",
      facing: 1, // 1 = facing right, -1 = mirrored
      eyeMode: "open", // open | wide | blink | happy | squint | closed
      pupilX: 0, // -1..1, world direction (renderer handles mirroring)
      pupilY: 0, // -1..1
      mark: null, // null | "!" | "z"
      markPhase: 0, // 0..1, animates the z's
      pivotY: BY, // grid row that squash/stretch/tilt pivot on (held: the scruff)
      sx: 1,
      sy: 1, // squash / stretch (mochi drag, landing bounce)
      tilt: 0,
      lift: 0 // hop height in grid cells (startle, landing)
    };
  }

  /* ------------------------------------------------------ PIXEL HELPERS */
  function cell(ctx, x, y) {
    ctx.fillRect(Math.round(x), Math.round(y), 1, 1);
  }
  function box(ctx, x0, y0, x1, y1) {
    ctx.fillRect(x0, y0, x1 - x0 + 1, y1 - y0 + 1);
  }

  // Eye whites / closed-eye shapes for one 3x3 eye box at (x, y)
  function drawEye(ctx, x, y, mode) {
    ctx.fillStyle = COLORS.EYE;
    if (mode === "open" || mode === "wide") {
      box(ctx, x, y, x + 2, y + 2);
      if (mode === "wide") {
        cell(ctx, x - 1, y + 1);
        cell(ctx, x + 3, y + 1);
      }
    } else if (mode === "blink") {
      box(ctx, x, y + 1, x + 2, y + 1);
    } else if (mode === "happy") {
      cell(ctx, x, y + 2);
      cell(ctx, x + 1, y + 1);
      cell(ctx, x + 2, y + 2);
    } else if (mode === "squint" || mode === "closed") {
      cell(ctx, x, y + 1);
      cell(ctx, x + 1, y + 2);
      cell(ctx, x + 2, y + 1);
    }
  }

  // "!" above the head, or two drifting z's
  function drawMark(ctx, pose) {
    if (!pose.mark) return;
    ctx.fillStyle = COLORS.MARK;
    if (pose.mark === "!") {
      box(ctx, 15, -6, 16, -2);
      box(ctx, 15, 0, 16, 1);
    } else if (pose.mark === "z") {
      var p = pose.markPhase;
      for (var k = 0; k < 2; k++) {
        var q = (p + k * 0.5) % 1;
        if (q > 0.85) continue;
        var zx = Math.round(23 + q * 6);
        var zy = Math.round(10 - q * 14);
        box(ctx, zx, zy, zx + 2, zy);
        cell(ctx, zx + 1, zy + 1);
        box(ctx, zx, zy + 2, zx + 2, zy + 2);
      }
    }
  }

  function frameOf(name) {
    return FRAMES[name] || FRAMES.sit;
  }

  /* ================================================== TWO-CANVAS MOUNT === */
  function makeBuffer(w, h) {
    var c = document.createElement("canvas");
    c.width = w;
    c.height = h;
    return c;
  }
  function setSize(canvas, scale) {
    canvas.width = (GRID + PAD * 2) * scale;
    canvas.height = (GRID + PAD * 2) * scale;
    canvas.style.width = canvas.width + "px";
    canvas.style.height = canvas.height + "px";
  }
  function createLayer(className) {
    var c = document.createElement("canvas");
    c.className = className;
    c.setAttribute("aria-hidden", "true");
    return c;
  }

  // Draw body layers of `pose` into logical-size buffers (unmirrored).
  function paintBody(buffers, pose) {
    var fr = frameOf(pose.frame);
    var mctx = buffers.mctx, octx = buffers.octx, dctx = buffers.dctx;
    [mctx, octx, dctx].forEach(function (b) {
      b.setTransform(1, 0, 0, 1, 0, 0);
      b.clearRect(0, 0, GRID, GRID);
    });
    // silhouette mask: body + light details
    mctx.fillStyle = COLORS.BODY;
    for (var y = 0; y < GRID; y++) {
      var row = fr.grid[y];
      for (var x = 0; x < GRID; x++) {
        var ch = row.charAt(x);
        if (ch === "#" || ch === "l") mctx.fillRect(x, y, 1, 1);
      }
    }
    // outline: the mask stamped in its 8 neighbours, tinted light
    for (var dy = -1; dy <= 1; dy++) {
      for (var dx = -1; dx <= 1; dx++) {
        if (dx || dy) octx.drawImage(buffers.mask, dx, dy);
      }
    }
    octx.globalCompositeOperation = "source-in";
    octx.fillStyle = COLORS.OUTLINE;
    octx.fillRect(0, 0, GRID, GRID);
    octx.globalCompositeOperation = "source-over";
    // details, whiskers, eyes, marks
    for (var yy = 0; yy < GRID; yy++) {
      var r2 = fr.grid[yy];
      for (var xx = 0; xx < GRID; xx++) {
        var c2 = r2.charAt(xx);
        if (c2 === "l") {
          dctx.fillStyle = COLORS.DETAIL;
          dctx.fillRect(xx, yy, 1, 1);
        } else if (c2 === "w") {
          dctx.fillStyle = COLORS.MARK;
          dctx.fillRect(xx, yy, 1, 1);
        }
      }
    }
    var mode = fr.closed ? "closed" : pose.eyeMode;
    for (var i = 0; i < fr.eyes.length; i++) drawEye(dctx, fr.eyes[i][0], fr.eyes[i][1], mode);
  }

  // Pupils: one cell inside each open eye, offset toward the cursor
  function paintPupils(buffers, pose) {
    var fr = frameOf(pose.frame);
    var pctx = buffers.pctx;
    pctx.setTransform(1, 0, 0, 1, 0, 0);
    pctx.clearRect(0, 0, GRID, GRID);
    if (fr.closed || (pose.eyeMode !== "open" && pose.eyeMode !== "wide")) return;
    var px = Math.max(-1, Math.min(1, Math.round(pose.pupilX * pose.facing)));
    var py = Math.max(-1, Math.min(1, Math.round(pose.pupilY)));
    pctx.fillStyle = COLORS.PUPIL;
    for (var i = 0; i < fr.eyes.length; i++) {
      pctx.fillRect(fr.eyes[i][0] + 1 + px, fr.eyes[i][1] + 1 + py, 1, 1);
    }
  }

  // Blit logical buffers onto a display context with facing, squash,
  // tilt and hop applied about the anchor (paw centre).
  function composite(target, sources, pose, scale, overlay) {
    target.setTransform(1, 0, 0, 1, 0, 0);
    target.clearRect(0, 0, target.canvas.width, target.canvas.height);
    target.imageSmoothingEnabled = false;
    var pivot = pose.pivotY == null ? BY : pose.pivotY;
    target.setTransform(scale, 0, 0, scale, 0, 0);
    target.translate(PAD + CX, PAD + pivot - pose.lift);
    target.rotate(pose.tilt);
    target.scale(pose.facing * pose.sx, pose.sy);
    for (var i = 0; i < sources.length; i++) target.drawImage(sources[i], -CX, -pivot);
    if (overlay) {
      // marks are drawn unmirrored so the "!" and z's always read correctly
      target.setTransform(scale, 0, 0, scale, 0, 0);
      target.translate(PAD, PAD - pose.lift);
      overlay(target);
    }
  }

  function makeBuffers() {
    var b = {
      mask: makeBuffer(GRID, GRID),
      outline: makeBuffer(GRID, GRID),
      detail: makeBuffer(GRID, GRID),
      pupils: makeBuffer(GRID, GRID)
    };
    b.mctx = b.mask.getContext("2d");
    b.octx = b.outline.getContext("2d");
    b.dctx = b.detail.getContext("2d");
    b.pctx = b.pupils.getContext("2d");
    return b;
  }

  // Builds the stacked body + eye canvases at `scale` screen px per
  // logical px. Both share one coordinate system so the caller can move
  // them with one transform and they stay aligned.
  function mount(scale) {
    var bodyCanvas = createLayer("kuro-body");
    var eyeCanvas = createLayer("kuro-eyes");
    setSize(bodyCanvas, scale);
    setSize(eyeCanvas, scale);
    var bodyCtx = bodyCanvas.getContext("2d");
    var eyeCtx = eyeCanvas.getContext("2d");
    var buffers = makeBuffers();

    function drawBody(pose, scaleNow) {
      refreshColors();
      paintBody(buffers, pose);
      composite(bodyCtx, [buffers.outline, buffers.mask, buffers.detail], pose, scaleNow, function (c) {
        drawMark(c, pose);
      });
    }
    function drawEyes(pose, scaleNow) {
      paintPupils(buffers, pose);
      composite(eyeCtx, [buffers.pupils], pose, scaleNow);
    }
    function resize(scaleNow) {
      setSize(bodyCanvas, scaleNow);
      setSize(eyeCanvas, scaleNow);
    }

    return { bodyCanvas: bodyCanvas, eyeCanvas: eyeCanvas, bodyCtx: bodyCtx, eyeCtx: eyeCtx, drawBody: drawBody, drawEyes: drawEyes, resize: resize };
  }

  /* ------------------------------------------------------- HIT TESTING */
  // Click-through: the canvases are pointer-events:none, so real links
  // underneath always get the click. js/kuro-state.js calls this from
  // document-level pointer listeners to know when the pointer is over an
  // actually opaque Kuro pixel.
  function hitTest(canvas, clientX, clientY) {
    var r = canvas.getBoundingClientRect();
    if (clientX < r.left || clientX > r.right || clientY < r.top || clientY > r.bottom) return false;
    var lx = Math.floor((clientX - r.left) * (canvas.width / r.width));
    var ly = Math.floor((clientY - r.top) * (canvas.height / r.height));
    try {
      return canvas.getContext("2d").getImageData(lx, ly, 1, 1).data[3] > 0;
    } catch (e) {
      return true;
    }
  }

  /* ----------------------------------------------------------- FAVICON */
  // 16px uses the hand-drawn face; larger sizes render the "peek" frame
  // (face + front paws) through the real renderer. Exported as data URLs,
  // so there is no committed favicon file.
  function renderFaviconDataURL(size) {
    refreshColors();
    var out = makeBuffer(size, size);
    var oc = out.getContext("2d");
    oc.imageSmoothingEnabled = false;
    oc.fillStyle = "#0c0c0f";
    oc.fillRect(0, 0, size, size);
    if (size <= 16) {
      var g = makeBuffer(16, 16), gc = g.getContext("2d");
      var fill = { 1: "#f4f4f5", 2: "#0a0a0a", 3: "#f4f4f5", 4: "#0a0a0a" };
      for (var y = 0; y < 16; y++) {
        for (var x = 0; x < 16; x++) {
          var ch = FAVICON_16[y].charAt(x);
          if (ch === "0") continue;
          gc.fillStyle = fill[ch];
          gc.fillRect(x, y, 1, 1);
        }
      }
      oc.drawImage(g, 0, 0, size, size);
      return out.toDataURL("image/png");
    }
    var saved = COLORS.OUTLINE;
    COLORS.OUTLINE = COLORS.EYE = COLORS.DETAIL = COLORS.MARK = "#f4f4f5"; // favicon always sits on a dark tile
    var pose = defaultPose();
    pose.frame = "peek";
    var b = makeBuffers();
    paintBody(b, pose);
    paintPupils(b, pose);
    var tile = makeBuffer(GRID, GRID), tc = tile.getContext("2d");
    [b.outline, b.mask, b.detail, b.pupils].forEach(function (s) {
      tc.drawImage(s, 0, 0);
    });
    // crop the face (rows 1-30, cols 1-30) into the square tile
    oc.drawImage(tile, 1, 1, 30, 30, 0, 0, size, size);
    COLORS.OUTLINE = saved;
    refreshColors();
    return out.toDataURL("image/png");
  }

  function installFavicon() {
    [16, 32, 180, 192].forEach(function (size) {
      var isTouch = size === 180;
      var id = "kuro-favicon-" + size;
      var link = document.getElementById(id);
      if (!link) {
        link = document.createElement("link");
        link.id = id;
        link.rel = isTouch ? "apple-touch-icon" : "icon";
        if (!isTouch) {
          link.type = "image/png";
          link.sizes = size + "x" + size;
        }
        document.head.appendChild(link);
      }
      link.href = renderFaviconDataURL(size);
    });
  }

  window.KuroRender = {
    GRID: GRID,
    CX: CX,
    BY: BY,
    PAD: PAD,
    COLORS: COLORS,
    FRAMES: FRAMES,
    refreshColors: refreshColors,
    defaultPose: defaultPose,
    mount: mount,
    setSize: setSize,
    hitTest: hitTest,
    installFavicon: installFavicon
  };
